8. Получить журнал записей начисления зарплат/дополнительных выплат агентам с указанием фамилии, числа месяца, года, суммы и типа выплаты (зарплата или вознаграждение за договор, см задача 2)


SELECT "Agent".family, t.day, t.month, t.year, t.value, t.type
	FROM "Agent"	
		INNER JOIN
		(
			SELECT 
				id_Agent, 
				null AS day, 
				month, 
				year,
				value,
				'Заработная плата' AS type,
			FROM "Salary"
			UNION
			SELECT 
				id_Agent, 
				extract (day from date) AS day, 
				extract (month from date) AS month, 
				extract (year from date) AS year, 
				sum*tarif AS value,
				'Вознаграждение' AS type
			FROM "Order"
		) AS t ON "Agent".id = t."id_Agent"


Комментарий. Журнал записей начисления зарплат/дополнительных выплат агентам формируется на основе двух таблиц: Salary (информация о заработной плате) и Order (иныормация о договорах и вознаграждении агентов). Так как нам надо вывести информацию из обеих таблиц в одном результате, используется операцию объединения UNION. Для каждой из исходных таблиц выполняем операцию проекции, так как количество столбцов, участвующих в UNION, должно быть одинаковым. Обратите внимание, в каждую из таблиц участвующих в объединении, добавляется новый столбец type на основе строковой констранты ('Заработная плата' или 'Вознаграждение'). Так как по условию задачи требуется отобрать фамилию агента, а этого столбца нет ни в Salary ни в Order, выполняем соединение результата операции UNION (которая получает псевдоним t) с таблицей Agent в селекте самого верхнего уровня.