SELECT * FROM "Branch"				-- выборка из таблицы Филиал
SELECT * FROM "Agent"				-- выборка из таблицы Агент
SELECT * FROM "Client"				-- выборка из таблицы Клиент
SELECT * FROM "Insurance_type"			-- выборка из таблицы Виды страхования
SELECT * FROM "Order"				-- выборка из таблицы Договор
SELECT * FROM "Salary"				-- выборка из таблицы Зарплата

Комментарий. SELECT и FROM ключенвые слова, * означает оборазить все поля (без выполнениы операции прокции), после FROM указывается имя таблицы, из которой производится выборка. Выполнения оператора SELECT начинается со слова FROM, после чего выводится заданное количество столбцов (все столбцы в приведенных примерах)

2. Получить договоры, заключенные в 2020 году. Отобрать только столбцы number, date, sum. Для каждого договора получить столбец reward (вознаграждения для агента) по формуле reward = sum*tarif

SELECT number, date, sum, sum*tarif AS reward FROM "Order" WHERE extract(year from "date") = 2020 

Комментарий. В запросе присутствует операция выборки по условию (предложение WHERE) и операция проекции, в которой указываются необходимые для вывода столбцы. При этом столбец reward в изначальной таблице отсутствует и является вычисляемым. После клчюевого слова AS указывается спевдоним для вычисляемого столбца. Используется встроенная функция extract(year from ...) для извлчения года из даты.

