5. Получить полную информация о договорах за 2020 год, включая фамилию клиента, идентификатор агента, наименование филиала и наименовани видов страхования.

SELECT "Order".*, "Client"."family", "Agent"."id" AS "agent_id", "Branch"."name" AS "branch_name", "Insurance_type"."name" AS "insurance_name"
	FROM "Order"
		INNER JOIN "Client" ON "Order"."passport_serie_Client" = "Client"."passport_serie" AND "Order"."passport_number_Client" = "Client"."passport_number"
		INNER JOIN "Agent"  ON "Order"."id_Agent" = "Agent"."id"
		LEFT  JOIN "Branch" ON "Agent"."id_Branch" = "Branch"."id"
		INNER JOIN "many_Order_has_many_Insurance_type" ON "Order"."number" = "many_Order_has_many_Insurance_type"."number_Order"
		INNER JOIN "Insurance_type" ON "Insurance_type"."id" = "many_Order_has_many_Insurance_type"."id_Insurance_type"
	WHERE extract(year from "Order"."date") = 2020

Комментарий. В запросе присутствует операция соединения всех необходимых таблицы по равенству первичного-внешного ключей. Связи с таблицыми "Client", "Agent", "many_Order_has_many_Insurance_type", "Insurance_type" обязательные, поэтому используется внутреннее соединение (INNER JOIN). Связь с таблицей "Branch" необязательная, следовательно во избежании потери данных используется левое внешнее соединение (LEFT OUTER JOIN). Если договор не включет виды страхований, он не отображается в результирующем запросе. После соединения таблиц происходит фильтрация по дате заключения договора (2020 год) и выводятся необходимые атрибуты вместе с указанием таблиц. Для идентификатора агента, наименования филиала и наименования видов страхования вводятся псеводонимы (ключевое слово AS). Так как в одном договоре может быть несколько видов страхований, результат запроса будет содержать повторяющиеся строки.

6. Получить филиалы, в которых не было заключено ни одного договора

SELECT "Branch".*
	FROM "Branch" 
		LEFT JOIN "Agent" ON "Branch"."id" = "Agent"."id_Branch"
		LEFT JOIN "Order" ON "Agent"."id" = "Order"."id_Agent"
	WHERE "Order"."number" IS NULL

Комментарий. Связи Филиал-Агент и Агент-Договор являются необзательными (т.е. могут существовать филиалы буз агентов и агенты, не заключившие договоры). Таким образом наилучшим вариантом будет являться использование левого внешнего соединения: в любом случае все филиалы, указанные в БД попадут в результат, но филиалы, у которых нет ни одного заключенного договора будут иметь значение атрибута "Order"."number" равным NULL, что и отслеживается соответствующим фильтром в предложении WHERE. 

7. Найти виды страхования, на которые не заключалось ни одного договора в 2023 году. Отобразить только id и наименование вида страхования

SELECT id, name FROM "Insurance_type"
EXCEPT
SELECT "Insurance_type".id, "Insurance_type".name 
	FROM "Order" 
		INNER JOIN "many_Order_has_many_Insurance_type" ON "Order"."number" = "many_Order_has_many_Insurance_type"."number_Order"
		INNER JOIN "Insurance_type" ON "Insurance_type"."id" = "many_Order_has_many_Insurance_type"."id_Insurance_type"
	WHERE extract(year from "Order"."date") = 2023

Комментарий. Задача сводится к выполнению следующего алгоритма: из множества всех вообще видов страхования в таблице "Insurance_type" вычесть множество видов страхований, на которые были заключены договоры в 2023 году. Все виды страхования можно получить с помощь простого SELECT из таблицы "Insurance_type". Виды страхования, на которые заключен договор в 2023 году находятся соединением 3-х таблиц: "Order" для фильтрации по году, "Insurance_type" для столбца с наименованием вида страхования, "many_Order_has_many_Insurance_type" как связующая таблица в отношении "многие-ко-многим". После соединения данные фильтруются по году заключения договора. Разность множеств выполняется с помощью оператора EXCEPT.

8. Получить журнал записей начисления зарплат/дополнительных выплат агентам с указанием фамилии, числа месяца, года, суммы и типа выплаты (зарплата или вознаграждение за договор, см задача 2)


SELECT "Agent".family, t.day, t.month, t.year, t.value, t.type
	FROM "Agent"	
		INNER JOIN
		(
			SELECT 
				id_Agent, 
				null AS day, 
				month, 
				year,
				value,
				'Заработная плата' AS type,
			FROM "Salary"
			UNION
			SELECT 
				id_Agent, 
				extract (day from date) AS day, 
				extract (month from date) AS month, 
				extract (year from date) AS year, 
				sum*tarif AS value,
				'Вознаграждение' AS type
			FROM "Order"
		) AS t ON "Agent".id = t."id_Agent"


Комментарий. Журнал записей начисления зарплат/дополнительных выплат агентам формируется на основе двух таблиц: Salary (информация о заработной плате) и Order (иныормация о договорах и вознаграждении агентов). Так как нам надо вывести информацию из обеих таблиц в одном результате, используется операцию объединения UNION. Для каждой из исходных таблиц выполняем операцию проекции, так как количество столбцов, участвующих в UNION, должно быть одинаковым. Обратите внимание, в каждую из таблиц участвующих в объединении, добавляется новый столбец type на основе строковой констранты ('Заработная плата' или 'Вознаграждение'). Так как по условию задачи требуется отобрать фамилию агента, а этого столбца нет ни в Salary ни в Order, выполняем соединение результата операции UNION (которая получает псевдоним t) с таблицей Agent в селекте самого верхнего уровня.